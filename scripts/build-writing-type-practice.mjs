import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const sourceRoot =
  process.argv[2] ?? "/Users/shidianjin/Desktop/雅思写作/小作文";
const outputPath = path.resolve(
  process.cwd(),
  "src/data/writing/task1-type-practice.json",
);

const folders = [
  ["line graph", "line-graph", "折线图"],
  ["bar chart", "bar-chart", "柱状图"],
  ["pie chart", "pie-chart", "饼图"],
  ["table", "table", "表格"],
  ["map", "map", "地图题"],
  ["diagram or process", "process", "流程图"],
  ["multiple task", "mixed", "混合图"],
];

const manuallyCuratedImages = new Set([
  "line graph/The consumption of three spreads from 1981 to 2007.png",
  "line graph/The hospital admissions for five hospitals in the European country from 2004 to 2018.png",
  "bar chart/The average monthly expenditure by British households in three years.png",
  "bar chart/The amount of energy generated by wind in four countries from 1985 to 2000.png",
  "pie chart/The comparison of different kinds of energy production of France in two years.png",
  "pie chart/The electricity generation in two countries in 2009.png",
  "table/the number of full-time students from India who studied at various university in the UK.png",
  "table/Results of two surveys done in 1980 and 2010 on various aspects of city living in a particular city.png",
  "map/the changes that have taken place In Meadowside Village and Fountain, a neighboring town since 1962.png",
  "diagram or process/The stages and equipment used in the cement-making process and how cement is used to produce concrete for building purposes.png",
  "diagram or process/The life cycle of a frog.png",
  "multiple task/The distribution of the world's water and the use of water in three countries.png",
  "multiple task/What history graduates did after completing their undergraduate degree course from a university in the UK.png",
]);

const instruction =
  "Summarise the information by selecting and reporting the main features, and make comparisons where relevant.";
const items = [];

for (const [folder, category, label] of folders) {
  const filenames = (await readdir(path.join(sourceRoot, folder)))
    .filter((filename) => /\.(png|jpe?g)$/i.test(filename))
    .sort((a, b) => a.localeCompare(b, "en"));
  const filenameLookup = new Map(
    filenames.map((filename) => [filename.toLocaleLowerCase(), filename]),
  );
  const questionFiles = filenames.filter((filename) => {
    const relativeName = `${folder}/${filename}`;
    return (
      !manuallyCuratedImages.has(relativeName) &&
      !/-model answer\.(png|jpe?g)$/i.test(filename) &&
      !/-answers?\.(png|jpe?g)$/i.test(filename) &&
      !/-practice\.(png|jpe?g)$/i.test(filename) &&
      !/^tips\./i.test(filename) &&
      !/^WX/i.test(filename) &&
      !/^How hydroelectric power is generated-[2-5]\./i.test(filename)
    );
  });

  questionFiles.forEach((filename, index) => {
    const extension = path.extname(filename);
    const title = path.basename(filename, extension).replace(/\.+$/, "");
    const answerCandidates = [
      `${title}-model answer.png`,
      `${title}-model answer.jpg`,
      `${title}-answers.png`,
      `${title}-answer.png`,
    ];
    const answerFilename = answerCandidates
      .map((candidate) => filenameLookup.get(candidate.toLocaleLowerCase()))
      .find(Boolean);
    const publicRoot = `/writing/task1/by-type/${folder}`;

    items.push({
      id: `type-${category}-folder-${String(index + 1).padStart(2, "0")}`,
      book: "题型专项",
      test: answerFilename ? "附范文" : "题型范文",
      task: "task1",
      category,
      title,
      shortTitle: `${label}专项练习`,
      prompt: instruction,
      image: `${publicRoot}/${filename}`,
      ...(answerFilename
        ? { answerImage: `${publicRoot}/${answerFilename}` }
        : {}),
      wordTarget: 150,
    });
  });
}

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, `${JSON.stringify(items, null, 2)}\n`, "utf8");
console.log(`Indexed ${items.length} Task 1 practice questions -> ${outputPath}`);
